#!/usr/bin/env python3
"""Independent short-horizon verification for the three-regime FX model.

The reference calculations enumerate every state path. They deliberately avoid
forward/backward and moment-recursion formulas used by the production model.
The small fixtures test those recursions, not statistical predictive accuracy.
"""
from itertools import product
import math
import json
import numpy as np


def enumerated_observation_posterior(observations, means, variances, transition, prior):
    """Exact likelihood, smoothing, adjacent probabilities by state-path sum."""
    observations = np.asarray(observations, dtype=float)
    means = np.asarray(means, dtype=float)
    variances = np.asarray(variances, dtype=float)
    transition = np.asarray(transition, dtype=float)
    prior = np.asarray(prior, dtype=float)
    count, states = len(observations), len(prior)
    posterior = np.zeros((count, states))
    adjacent = np.zeros((max(count - 1, 0), states, states))
    likelihood = 0.0
    for path in product(range(states), repeat=count):
        probability = prior[path[0]]
        for t, state in enumerate(path):
            if t:
                probability *= transition[path[t - 1], state]
            residual = observations[t] - means[state]
            probability *= math.exp(-residual * residual / (2 * variances[state])) / math.sqrt(2 * math.pi * variances[state])
        likelihood += probability
        for t, state in enumerate(path):
            posterior[t, state] += probability
            if t:
                adjacent[t - 1, path[t - 1], state] += probability
    return math.log(likelihood), posterior / likelihood, adjacent / likelihood


def enumerated_forecast(initial, means, variances, transition, steps):
    """Exact distribution moments by enumerating S0,...,Sh.

    Initial probabilities apply to S0, the final observed state. The first
    future return is generated by S1 after a transition from S0.
    """
    initial = np.asarray(initial, dtype=float)
    means = np.asarray(means, dtype=float)
    variances = np.asarray(variances, dtype=float)
    transition = np.asarray(transition, dtype=float)
    components = []
    states = len(initial)
    final = np.zeros(states)
    for path in product(range(states), repeat=steps + 1):
        probability = initial[path[0]]
        log_mean = 0.0
        log_variance = 0.0
        for t in range(1, steps + 1):
            probability *= transition[path[t - 1], path[t]]
            log_mean += means[path[t]]
            log_variance += variances[path[t]]
        components.append((probability, log_mean, log_variance))
        final[path[-1]] += probability
    mass = sum(p for p, _, _ in components)
    mean = sum(p * m for p, m, _ in components)
    second = sum(p * (v + m * m) for p, m, v in components)
    level_first = sum(p * math.exp(m + v / 2) for p, m, v in components)
    level_second = sum(p * math.exp(2 * m + 2 * v) for p, m, v in components)
    return {
        "probability_mass": mass,
        "probabilities": final,
        "log_mean": mean,
        "log_variance": second - mean * mean,
        "innovation_variance": sum(p * v for p, _, v in components),
        "expected_multiplier": level_first,
        "level_multiplier_variance": level_second - level_first * level_first,
        "components": components,
    }


def exact_log_quantile(components, probability):
    """Invert the enumerated finite Gaussian mixture without simulation."""
    lower = min(m - 14 * math.sqrt(v) for _, m, v in components)
    upper = max(m + 14 * math.sqrt(v) for _, m, v in components)
    for _ in range(90):
        middle = (lower + upper) / 2
        cdf = sum(p * (1 + math.erf((middle - m) / math.sqrt(2 * v))) / 2 for p, m, v in components)
        if cdf < probability:
            lower = middle
        else:
            upper = middle
    return (lower + upper) / 2


def one_step_total_variance(initial, means, variances, transition):
    # Independent scalar law of total variance; transition orientation matters.
    probability = [sum(initial[i] * transition[i][j] for i in range(len(initial))) for j in range(len(initial))]
    mean = sum(p * m for p, m in zip(probability, means))
    within = sum(p * v for p, v in zip(probability, variances))
    between = sum(p * (m - mean) ** 2 for p, m in zip(probability, means))
    return mean, within + between


def mixture_density(components, value):
    return sum(p * math.exp(-(value - m) ** 2 / (2 * v)) / math.sqrt(2 * math.pi * v) for p, m, v in components)


def main():
    from fx_markov import MarkovFit, forecast_markov, forecast_moments, forward_backward, mixture_quantile, weekday_dates

    initial = np.array([0.61, 0.11, 0.28])
    means = np.array([-0.015, 0.002, 0.020])
    variances = np.array([0.000004, 0.000009, 0.000100])
    transition = np.array([[0.88, 0.10, 0.02], [0.08, 0.69, 0.23], [0.04, 0.09, 0.87]])
    observations = np.array([-0.006, 0.003, 0.012, -0.004])

    expected_likelihood, expected_smoothing, expected_adjacency = enumerated_observation_posterior(observations, means, variances, transition, initial)
    likelihood, filtered, smoothed, counts = forward_backward(observations, means, variances, transition, initial)
    np.testing.assert_allclose(likelihood, expected_likelihood, atol=2e-12, rtol=0)
    np.testing.assert_allclose(smoothed, expected_smoothing, atol=2e-12, rtol=0)
    np.testing.assert_allclose(counts, expected_adjacency.sum(axis=0), atol=2e-12, rtol=0)
    for t in range(len(observations)):
        _, prefix_smoothing, _ = enumerated_observation_posterior(observations[:t + 1], means, variances, transition, initial)
        np.testing.assert_allclose(filtered[t], prefix_smoothing[-1], atol=2e-12, rtol=0)

    references = [enumerated_forecast(initial, means, variances, transition, horizon) for horizon in range(1, 5)]
    actual = forecast_moments(means, variances, transition, initial, 4)
    errors = {"logMean": 0.0, "logVariance": 0.0, "meanMultiplier": 0.0}
    for result, expected in zip(actual, references):
        np.testing.assert_allclose(expected["probability_mass"], 1, atol=2e-14, rtol=0)
        np.testing.assert_allclose(result["probs"], expected["probabilities"], atol=2e-14, rtol=0)
        for key, reference_key in (("logMean", "log_mean"), ("logVariance", "log_variance"), ("meanMultiplier", "expected_multiplier"), ("innovationVariance", "innovation_variance")):
            np.testing.assert_allclose(result[key], expected[reference_key], atol=2e-13, rtol=0)
            if key in errors:
                errors[key] = max(errors[key], abs(result[key] - expected[reference_key]))
        np.testing.assert_allclose(result["regimePathVariance"], expected["log_variance"] - expected["innovation_variance"], atol=2e-13, rtol=0)
    next_mean, next_variance = one_step_total_variance(initial.tolist(), means.tolist(), variances.tolist(), transition.tolist())
    np.testing.assert_allclose(actual[0]["logMean"], next_mean, atol=2e-14, rtol=0)
    np.testing.assert_allclose(actual[0]["logVariance"], next_variance, atol=2e-14, rtol=0)
    for probability in (.025, .05, .16, .5, .84, .95, .975):
        expected_quantile = exact_log_quantile(references[0]["components"], probability)
        actual_quantile = mixture_quantile(means, variances, initial @ transition, probability)
        np.testing.assert_allclose(actual_quantile, expected_quantile, atol=2e-14, rtol=0)

    # Absorbing regimes expose the h^2 variance of uncertain persistent drift.
    absorbing = forecast_moments(means, variances, np.eye(3), initial, 30)[-1]
    within = 30 * float(initial @ variances)
    between = 30 ** 2 * float(initial @ ((means - initial @ means) ** 2))
    np.testing.assert_allclose(absorbing["logVariance"], within + between, atol=2e-13, rtol=0)
    np.testing.assert_allclose(absorbing["meanMultiplier"], initial @ np.exp(30 * means + 15 * variances), atol=2e-13, rtol=0)

    # If emissions are identical, the chain must collapse to an ordinary normal sum.
    common_mean, common_variance = -0.001, 0.00004
    collapsed = forecast_moments(np.full(3, common_mean), np.full(3, common_variance), transition, initial, 504)[-1]
    np.testing.assert_allclose(collapsed["logMean"], 504 * common_mean, atol=2e-12, rtol=0)
    np.testing.assert_allclose(collapsed["logVariance"], 504 * common_variance, atol=2e-12, rtol=0)
    np.testing.assert_allclose(collapsed["meanMultiplier"], math.exp(504 * (common_mean + common_variance / 2)), atol=2e-12, rtol=0)

    # Monte Carlo quantiles are checked against exact finite-mixture CDF inversion.
    paths, spot = 120_000, 1300.0
    fit = MarkovFit(means, variances, transition, initial, np.array([initial]), np.array([initial]), 0.0, {})
    forecast, simulation, _ = forecast_markov(fit, spot, "2026-10-16", horizon=4, paths=paths, seed=9913)
    quantile_zscores = []
    for horizon in (1, 4):
        expected, point = references[horizon - 1], forecast[horizon - 1]
        np.testing.assert_allclose(point["mean"], spot * expected["expected_multiplier"], atol=1e-9, rtol=0)
        for key, probability in (("lower95", .025), ("lower90", .05), ("lower68", .16), ("median", .5), ("upper68", .84), ("upper90", .95), ("upper95", .975)):
            reference = exact_log_quantile(expected["components"], probability)
            observed = math.log(point[key] / spot)
            se = math.sqrt(probability * (1 - probability) / paths) / mixture_density(expected["components"], reference)
            z_score = abs(observed - reference) / se
            quantile_zscores.append(z_score)
            assert z_score < 6, (horizon, key, z_score)
    assert simulation["meanAgreementSE"] < 6, simulation
    assert simulation["varianceAgreementSE"] < 6, simulation
    assert weekday_dates("2026-10-16", 4) == ["2026-10-19", "2026-10-20", "2026-10-21", "2026-10-22"]
    assert forecast[0]["date"] == "2026-10-19"

    print(json.dumps({
        "status": "passed",
        "reference_method": "exhaustive state-path enumeration and exact Gaussian-mixture CDF inversion",
        "likelihood_abs_error": abs(likelihood - expected_likelihood),
        "moment_max_abs_error": errors,
        "exact_quantiles_checked": len(quantile_zscores),
        "one_step_analytic_quantiles_checked": 7,
        "max_quantile_monte_carlo_se": max(quantile_zscores),
        "simulation_mean_agreement_se": simulation["meanAgreementSE"],
        "simulation_variance_agreement_se": simulation["varianceAgreementSE"],
        "boundaries": ["absorbing regimes", "identical emission regimes", "Friday-to-Monday date projection"],
        "scope": "implementation mathematics, not out-of-sample predictive performance or empirical coverage",
    }, indent=2))


if __name__ == "__main__":
    main()
